using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Newtonsoft.Json.Linq;
using Puttshack.Domain;

namespace Puttshack.Content
{
    /// <summary>
    /// The C#/Python terrain parity golden: the course heightfield's features, fixed probe points (tees, cups, routes,
    /// surfaces, trees, across the coast and the chasm, and a seeded scatter over the ground grid) and the heights
    /// <see cref="TerrainModel"/> gives there. Doubles are written as IEEE bit patterns (16 hex digits) so every runtime
    /// reads exactly the same values; probe coordinates are multiples of 1/64 m, exact in plain decimal too.
    /// Checked by TerrainParityTests (C#) and ArtSource/Blender/scripts/test_terrain_parity.py (pp_pebble_terrain.py).
    /// </summary>
    public static class TerrainParity
    {
        public const int Format = 1;
        public const string GoldenPath = "Assets/_Game/Tests/EditMode/Fixtures/terrain_parity.golden.json";

        public static string Bits(double v) => BitConverter.DoubleToInt64Bits(v).ToString("x16", CultureInfo.InvariantCulture);

        public static double FromBits(string hex) => BitConverter.Int64BitsToDouble(long.Parse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture));

        public static string Golden(CourseDefinition course, IReadOnlyList<TerrainFeature> terrain)
        {
            var features = new JArray();
            foreach (TerrainFeature f in terrain) features.Add(Encode(f));
            var probes = new JArray();
            foreach (Vec2d p in Probes(course, terrain))
            {
                double h = TerrainModel.Height(terrain, p.x, p.z);
                probes.Add(new JArray(Exact(p.x), Exact(p.z), Bits(h), Math.Round(h, 6)));
            }
            var root = new JObject
            {
                ["Format"] = Format,
                ["Notes"] = "Generated by Puttshack > Course > Write Terrain Parity Golden. Numbers in Features and the third probe column are IEEE double bits; the fourth is the height rounded for reading.",
                ["Course"] = $"{course.Id} {course.Version}",
                ["Features"] = features,
                ["Probes"] = probes,
            };
            return root.ToString(Newtonsoft.Json.Formatting.None).Replace("],[", "],\n[") + "\n";
        }

        public static List<TerrainFeature> DecodeFeatures(JArray features)
        {
            var list = new List<TerrainFeature>();
            foreach (JObject o in features)
            {
                var f = new TerrainFeature
                {
                    Kind = (TerrainFeatureKind)Enum.Parse(typeof(TerrainFeatureKind), (string)o["Kind"]),
                    Center = V2((JArray)o["Center"]),
                    InnerRadius = FromBits((string)o["Inner"]),
                    OuterRadius = FromBits((string)o["Outer"]),
                    Height = FromBits((string)o["Height"]),
                    Slope = V2((JArray)o["Slope"]),
                };
                if (o["Path"] is JArray path)
                {
                    f.Path = new List<Vec2d>();
                    foreach (JArray p in path) f.Path.Add(V2(p));
                }
                list.Add(f);
            }
            return list;
        }

        private static JObject Encode(TerrainFeature f)
        {
            var o = new JObject
            {
                ["Kind"] = f.Kind.ToString(),
                ["Center"] = new JArray(Bits(f.Center.x), Bits(f.Center.z)),
                ["Inner"] = Bits(f.InnerRadius),
                ["Outer"] = Bits(f.OuterRadius),
                ["Height"] = Bits(f.Height),
                ["Slope"] = new JArray(Bits(f.Slope.x), Bits(f.Slope.z)),
            };
            if (f.Path != null)
            {
                var path = new JArray();
                foreach (Vec2d p in f.Path) path.Add(new JArray(Bits(p.x), Bits(p.z)));
                o["Path"] = path;
            }
            return o;
        }

        private static Vec2d V2(JArray a) => new Vec2d(FromBits((string)a[0]), FromBits((string)a[1]));

        private static JToken Exact(double v) => v == Math.Floor(v) ? new JValue((long)v) : new JValue(decimal.Parse(v.ToString("0.######", CultureInfo.InvariantCulture), CultureInfo.InvariantCulture));

        private static double Snap(double v) => Math.Round(v * 64) / 64;

        private static IEnumerable<Vec2d> Probes(CourseDefinition course, IReadOnlyList<TerrainFeature> terrain)
        {
            var seen = new HashSet<(double, double)>();
            var points = new List<Vec2d>();
            void Add(double x, double z)
            {
                x = Snap(x);
                z = Snap(z);
                if (seen.Add((x, z))) points.Add(new Vec2d(x, z));
            }

            double minX = double.MaxValue, minZ = double.MaxValue, maxX = double.MinValue, maxZ = double.MinValue;
            foreach (HoleDefinition hole in course.Holes)
            {
                Add(hole.TeeM.x, hole.TeeM.z);
                Add(hole.CupM.x, hole.CupM.z);
                foreach (Vec3d p in hole.PlayRouteM) Add(p.x, p.z);
                foreach (SurfaceRegion r in hole.Surfaces)
                {
                    if (r.Polygon.Count == 0) continue;
                    double cx = 0, cz = 0;
                    foreach (Vec2d p in r.Polygon) { cx += p.x; cz += p.z; }
                    Add(cx / r.Polygon.Count, cz / r.Polygon.Count);
                    Add(r.Polygon[0].x, r.Polygon[0].z);
                    Add(r.Polygon[r.Polygon.Count / 2].x, r.Polygon[r.Polygon.Count / 2].z);
                }
                foreach (TreeObstacle t in hole.Trees) Add(t.Position.x, t.Position.z);
                foreach (DropPoint d in hole.Drops) Add(d.Position.x, d.Position.z);
                foreach (Vec2d p in hole.PlayableBoundary)
                {
                    minX = Math.Min(minX, p.x);
                    maxX = Math.Max(maxX, p.x);
                    minZ = Math.Min(minZ, p.z);
                    maxZ = Math.Max(maxZ, p.z);
                }
            }

            // Across every shelf (cliff face, beach, sea floor), on both sides and right at the edge.
            foreach (TerrainFeature f in terrain)
            {
                if (f.Kind != TerrainFeatureKind.Shelf || f.Path == null) continue;
                for (int i = 0; i + 1 < f.Path.Count; i += 8)
                {
                    Vec2d a = f.Path[i], b = f.Path[i + 1];
                    double dx = b.x - a.x, dz = b.z - a.z, len = Math.Sqrt(dx * dx + dz * dz);
                    if (len < 1e-9) continue;
                    double nx = -dz / len, nz = dx / len;
                    foreach (double d in new[] { -12.0, -2.5, 0.25, 1.5, 3.5, 6.0, 9.0, 14.0, 22.0, 35.0 })
                        Add((a.x + b.x) / 2 + nx * d, (a.z + b.z) / 2 + nz * d);
                }
            }

            // Seeded scatter over the ground grid rectangle (boundaries plus 30 m).
            minX -= 30;
            minZ -= 30;
            maxX += 30;
            maxZ += 30;
            uint seed = 0x9E3779B9u;
            for (int i = 0; i < 800; i++)
            {
                seed = seed * 1664525u + 1013904223u;
                double u = (seed >> 8) / 16777216.0;
                seed = seed * 1664525u + 1013904223u;
                double v = (seed >> 8) / 16777216.0;
                Add(minX + u * (maxX - minX), minZ + v * (maxZ - minZ));
            }
            return points;
        }
    }
}
